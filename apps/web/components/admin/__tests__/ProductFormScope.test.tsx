import {render, screen} from '@testing-library/react';
import {describe, it, expect, vi} from 'vitest';
import ProductForm from '../ProductForm';

// Форма пишет строку ВАРИАНТА (`products`), а страница товара берёт имя и
// описание из МОДЕЛИ (`product_models`). При этом цена и наличие из той же
// формы работают, поэтому на вид поля неотличимы: сохранение проходит, поле
// записывается, страница не меняется. Подпись — единственное, что отделяет
// владельца от уверенности, что он переименовал товар.
//
// НО ПОДПИСЬ ОБЯЗАНА БЫТЬ РАЗНОЙ У РАЗНЫХ ПОЛЕЙ, и это выяснилось 15.09.
// Общая пометка «на сайте не показывается» стояла у всех трёх, и про
// НАЗВАНИЕ она была ложью: `products.title` читают корзина (CartService),
// заказ (OrderService), избранное, выгрузка по 152-ФЗ (AuthService), письма о
// складе и — главное — строка ФИСКАЛЬНОГО ЧЕКА ЮKassa
// (CheckoutService.buildPaymentRequest, утверждается CheckoutServiceTest).
//
// То есть подпись говорила владельцу «неважно» про имя, которое печатается в
// документе покупателя. Мёртвое поле с честной подписью безобидно; живое поле
// с подписью «не показывается» — приглашение написать туда заглушку.
//
// Ошибка была не в наблюдении, а в его ширине: «пишет в пустоту» верно для
// ОДНОГО пути из семи, а прочитано как свойство поля.

vi.mock('next/navigation', () => ({
  usePathname: () => '/ru/admin/products/new',
  useRouter: () => ({push: vi.fn()}),
}));

// Ключ отдаётся как есть — так тест утверждает, что нужный ключ ВЫЗВАН, а не
// что совпал русский текст: переписывание формулировки не должно ронять
// сторож, а удаление подписи должно.
vi.mock('next-intl', () => ({
  useTranslations: () => (key: string) => key,
}));

vi.mock('../../../lib/api', () => ({
  apiFetch: vi.fn().mockResolvedValue({ok: true, json: async () => []}),
}));

vi.mock('../ImageUpload', () => ({default: () => null}));

describe('форма товара честно говорит, что доходит до сайта', () => {
  it('над формой стоит оговорка про область действия полей', () => {
    render(<ProductForm isNew />);
    expect(screen.getByText('scopeNotice')).toBeInTheDocument();
  });

  it('подзаголовок и описание помечены как не показываемые на странице товара', () => {
    render(<ProductForm isNew />);
    // Ровно два, а не три: название отсюда ушло, у него своя подпись. Цена и
    // наличие пометки не несут — они на сайт попадают, и лишняя пометка
    // соврала бы в другую сторону.
    expect(screen.getAllByText('notOnSite')).toHaveLength(2);
  });

  it('у названия СВОЯ подпись — оно печатается в чеке, а не пропадает', () => {
    render(<ProductForm isNew />);

    // Ровно то место, где общая подпись врала. Мутация «верни название под
    // общий ключ» красит этот тест и предыдущий разом.
    expect(screen.getByText('titleHint')).toBeInTheDocument();
    expect(screen.queryAllByText('notOnSite')).toHaveLength(2);
  });
});
