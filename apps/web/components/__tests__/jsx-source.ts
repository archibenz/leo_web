// Разбор JSX по исходнику — для сторожей, которые читают разметку, а не рендер.
//
// Эти два помощника выглядят мелочью, но каждый из них написан из-за
// конкретного ТИХОГО отказа, а не из любви к аккуратности.

/**
 * Тело открывающего тега — от позиции `from` до закрывающей `>` ЭТОГО тега.
 *
 * Не регулярным выражением: в атрибутах живут стрелки `=>` и вложенные `{...}`,
 * и `[^>]*` обрывает разбор на первой же стрелке. Обрыв не виден глазом — он
 * даёт «атрибут не найден», то есть сторож молча считает элемент безымянным и
 * пропускает. Отказ в сторону зелёного, самый дорогой вид.
 */
export function телоТега(source: string, from: number): string | null {
  let глубина = 0;
  let кавычка: string | null = null;
  for (let i = from; i < source.length; i++) {
    const c = source[i]!;
    if (кавычка !== null) {
      if (c === кавычка && source[i - 1] !== '\\') кавычка = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') кавычка = c;
    else if (c === '{') глубина++;
    else if (c === '}') глубина--;
    else if (c === '>' && глубина === 0) return source.slice(from, i);
  }
  return null;
}

/**
 * Комментарии — пробелами той же длины, чтобы номера строк не поехали.
 *
 * В шапках здешних файлов элементы упоминаются словами («<SidebarTrigger> без
 * aria-label»), и без этого сторож ловит их как настоящие вызовы. Ложная
 * тревога хуже пропуска ровно наполовину: пропуск молчит, а тревога учит не
 * верить сторожу.
 */
export function безКомментариев(source: string): string {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/^([ \t]*)\/\/.*$/gm, (m, отступ: string) => отступ + ' '.repeat(m.length - отступ.length));
}
