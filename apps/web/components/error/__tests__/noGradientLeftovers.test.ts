import {describe, expect, it} from 'vitest';
import {readFileSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

// Два экрана, которые владелец встречает в худшую минуту: авария и ожидание.
//
// Оба до 17.09 оставались из градиентной эпохи, хотя весь сайт вокруг уже
// белый. Экран 500 заливался #1e120d с кремовым текстом; экран загрузки
// АДМИНКИ — тем же #1E120D плюс золотое свечение, красный отсвет и виньетка,
// затемнявшая углы. Замерено снимком, а не прочитано по классам: первый мой
// замер поймал вообще другой экран (страницу ошибки группы витрины), потому
// что предпросмотр падал на чужой ошибке. Второй показал правду.
//
// ЗАПРЕТ НАЗЫВАЕТ СЛУЧАЙ, А НЕ НОСИТЕЛЯ. «Этот файл можно» переживает любую
// правку внутри файла и молчит о ней — на таком исключении сторож золота
// два дня не видел кнопок shadcn. Поэтому ниже перечислены КОНКРЕТНЫЕ токены
// прежней темы, и любой из них в этих двух местах — поломка.
const ТЁМНЫЕ_СЛЕДЫ = [
  '--paper-base',
  '--paper-muted',
  '--err-gold',
  '--err-rust',
  '--err-ink-muted',
  'bg-paper',
  'text-ink',
  'bg-accent',
];

const корень = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

function блокАварии(): string {
  const css = readFileSync(join(корень, 'app/globals.css'), 'utf8');
  const от = css.indexOf('.err2 {');
  const до = css.indexOf('@keyframes wb-ripple', от);
  expect(от, 'блок .err2 не найден — сторож остался бы зелёным по пустоте').toBeGreaterThan(-1);
  expect(до, 'конец блока .err2 не найден — разбор оборвался').toBeGreaterThan(от);
  return css.slice(от, до);
}

describe('экраны аварии и ожидания — в языке витрины', () => {
  it('экран 500 не тащит ни одного следа прежней темы', () => {
    const блок = блокАварии();
    const найдено = ТЁМНЫЕ_СЛЕДЫ.filter((т) => блок.includes(т));

    expect(найдено, 'экран аварии снова красится градиентной палитрой').toEqual([]);
  });

  it('экран 500 набран чернилами витрины, а не «чем-нибудь светлым»', () => {
    const блок = блокАварии();

    // Не только «нет тёмного», но и «есть нужное»: пустой блок прошёл бы
    // первую проверку и провалил бы экран.
    expect(блок).toMatch(/background:\s*#fff/);
    expect(блок).toMatch(/color:\s*#1c1714/);
    expect(блок).toMatch(/#776e64/);
  });

  it('экран загрузки админки не тащит следов прежней темы', () => {
    const источник = readFileSync(join(корень, 'components/LoaderSplash.tsx'), 'utf8');
    // Комментарий в файле перечисляет прежние токены, объясняя, что было;
    // проверяем разметку, а не объяснение.
    const разметка = источник.replace(/\/\/[^\n]*/g, '').replace(/\{\/\*[\s\S]*?\*\/\}/g, '');
    const найдено = ТЁМНЫЕ_СЛЕДЫ.filter((т) => разметка.includes(т));

    expect(найдено, 'экран ожидания снова из градиентной эпохи').toEqual([]);
    expect(разметка).toMatch(/bg-white/);
  });

  it('виньетки и свечения на экране ожидания нет', () => {
    const источник = readFileSync(join(корень, 'components/LoaderSplash.tsx'), 'utf8');
    const разметка = источник.replace(/\/\/[^\n]*/g, '').replace(/\{\/\*[\s\S]*?\*\/\}/g, '');

    expect(разметка).not.toMatch(/radial-gradient/);
    expect(разметка).not.toMatch(/rgba\(8,\s*4,\s*2/);
  });
});
