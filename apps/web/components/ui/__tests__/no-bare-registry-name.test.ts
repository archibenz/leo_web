import {describe, expect, it} from 'vitest';
import {readdirSync, readFileSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {безКомментариев, телоТега} from '../../__tests__/jsx-source';

// Примитив реестра приносит своё имя, и оно английское.
//
// НАХОДКА, С КОТОРОЙ СТОРОЖ НАЧАЛСЯ. На /ru/admin единственный <nav> на
// странице назывался «breadcrumb»: shadcn ставит своему корню
// aria-label="breadcrumb", наш вызов шёл голым, и читалка в русской админке
// произносила английское слово. Глазом это не видно вовсе — ни пикселя на
// экране, — поэтому нашлось обходом, а не осмотром.
//
// Соседний случай устроен наоборот и объясняет, зачем правило вообще нужно:
// у SidebarTrigger внутри лежит <span className="sr-only">Toggle Sidebar</span>,
// и наша обёртка CustomSidebarTrigger перекрывает его своим aria-label. То
// есть русское имя там приходит ОТ НАС, а не от примитива: смонтируй
// SidebarTrigger напрямую — и получишь английское имя молча.
//
// ПОЧЕМУ НЕ КОММЕНТАРИЙ. Комментарий держится на том, что его прочтут. За
// сутки до этого мы поймали три записи, которые честно написали и которые не
// сработали: подпись, пережившую предмет; расписание, разошедшееся с кодом;
// строку «e2e в CI не гоняется», устаревшую назавтра.
//
// ПОЧЕМУ НЕ ПРАВКА В САМОМ ПРИМИТИВЕ. components/ui/* принадлежит реестру:
// `npx shadcn add <имя>` перезаписывает файл целиком вместе с нашей правкой,
// молча. Поэтому имя чинится НА ВЫЗОВЕ, а сторож стоит на вызовах.

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const ПРИМИТИВЫ = join(КОРЕНЬ, 'components', 'ui');

type Находка = {примитив: string; имя: string; файл: string; как: 'sr-only' | 'aria-label'};

const ОБРАЗЦЫ = [
  [/className="sr-only">([A-Za-z][^<]*)</g, 'sr-only'],
  [/aria-label="([A-Za-z][^"]*)"/g, 'aria-label'],
] as const;

/**
 * Инвентарь английских имён в примитивах реестра — ВЫВЕДЕННЫЙ, не
 * перечисленный руками.
 *
 * Это и есть половина смысла сторожа: примитивов будет больше, и список,
 * написанный руками, устареет молча. Выведенный — краснеет сам, как только
 * реестр принесёт новое имя.
 *
 * Владелец имени определяется ближайшим объявлением выше по файлу. Приём
 * держится на том, что файлы реестра устроены единообразно (`const Имя =
 * React.forwardRef(...)`), и проверен на всех шести находках.
 */
function инвентарь(): Находка[] {
  const out: Находка[] = [];
  for (const файл of readdirSync(ПРИМИТИВЫ).filter((n) => n.endsWith('.tsx'))) {
    const source = безКомментариев(readFileSync(join(ПРИМИТИВЫ, файл), 'utf8'));
    const строки = source.split('\n');
    const владелец = (индекс: number): string => {
      for (let i = индекс; i >= 0; i--) {
        const m = /^(?:const|function)\s+([A-Z]\w*)/.exec(строки[i]!);
        if (m) return m[1]!;
      }
      return '?';
    };
    for (const [re, как] of ОБРАЗЦЫ) {
      const поиск = new RegExp(re.source, re.flags);
      let m: RegExpExecArray | null;
      while ((m = поиск.exec(source))) {
        const строка = source.slice(0, m.index).split('\n').length - 1;
        out.push({примитив: владелец(строка), имя: m[1]!, файл, как});
      }
    }
  }
  return out;
}

const ключ = (н: Находка) => `${н.примитив}|${н.имя}`;

// Записанное суждение по КАЖДОЙ находке: что она означает и попадает ли под
// правило. Здесь не список разрешённого, а разбор — иначе сторож превратится
// в «эти шесть можно», и седьмая проедет вместе с ними.
//
// `подПравилом` истинно там, где имя сидит на СОБСТВЕННОМ корне примитива и
// корень раздаёт `{...props}`, то есть вызов может его перекрыть. Где имя
// принадлежит вложенной кнопке (Close у диалога и шторки), вызов бессилен:
// это отдельная беда, и правилом «поставь aria-label» она не лечится.
const ЗАПИСАНО: Record<string, {подПравилом: boolean; почему: string}> = {
  'Breadcrumb|breadcrumb': {
    подПравилом: true,
    почему: 'имя на корневом <nav>, {...props} идёт после него — вызов перекрывает',
  },
  'SidebarTrigger|Toggle Sidebar': {
    подПравилом: true,
    почему: 'sr-only внутри кнопки, aria-label вызова перебивает его при вычислении имени',
  },
  'BreadcrumbEllipsis|More': {
    подПравилом: false,
    почему: 'весь элемент aria-hidden="true" — имя не произносится вовсе',
  },
  'DialogContent|Close': {
    подПравилом: false,
    почему: 'имя у ВЛОЖЕННОЙ кнопки закрытия, снаружи её не достать; лечится обёрткой, не правилом',
  },
  'SheetContent|Close': {
    подПравилом: false,
    почему: 'то же, что у диалога',
  },
  'SidebarRail|Toggle Sidebar': {
    подПравилом: false,
    почему: 'примитив не смонтирован ни одним вызовом — мёртвый код реестра',
  },
};

/**
 * Файлы, где примитивы ВЫЗЫВАЮТ.
 *
 * Исключения — по случаю, а не по имени папки:
 *
 * 1. `components/ui` — это ОПРЕДЕЛЕНИЕ примитива, а не место вызова. Требовать
 *    aria-label там значит требовать от реестра починить себя, и правка всё
 *    равно уедет со следующим `shadcn add`.
 * 2. Тесты — сторож мерит боевой код. Найдя сам себя, он был бы выполнен с
 *    рождения: у нас уже был такой, искавший строку по дереву и находивший
 *    собственный исходник.
 */
function вызовы(): string[] {
  const out: string[] = [];
  const пропустить = (путь: string) =>
    путь.includes('components/ui/') || путь.includes('__tests__') || /\.test\.tsx?$/.test(путь);
  const обойти = (каталог: string) => {
    for (const e of readdirSync(каталог, {withFileTypes: true})) {
      const путь = join(каталог, e.name);
      if (e.isDirectory()) {
        if (e.name !== 'node_modules') обойти(путь);
      } else if (e.name.endsWith('.tsx') && !пропустить(путь)) {
        out.push(путь);
      }
    }
  };
  обойти(join(КОРЕНЬ, 'app'));
  обойти(join(КОРЕНЬ, 'components'));
  return out;
}

type Вызов = {примитив: string; файл: string; строка: number; сИменем: boolean};

function найтиВызовы(примитивы: string[]): Вызов[] {
  const out: Вызов[] = [];
  for (const путь of вызовы()) {
    const source = безКомментариев(readFileSync(путь, 'utf8'));
    for (const примитив of примитивы) {
      const re = new RegExp(`<${примитив}(?=[\\s/>])`, 'g');
      for (const m of source.matchAll(re)) {
        const attrs = телоТега(source, m.index + примитив.length + 1);
        if (attrs === null) continue;
        out.push({
          примитив,
          файл: путь.slice(КОРЕНЬ.length + 1),
          строка: source.slice(0, m.index).split('\n').length,
          сИменем: /\baria-label\s*=/.test(attrs),
        });
      }
    }
  }
  return out;
}

describe('английское имя примитива реестра не доезжает до экрана', () => {
  const найдено = инвентарь();
  const подПравилом = Object.entries(ЗАПИСАНО)
    .filter(([, з]) => з.подПравилом)
    .map(([k]) => k.split('|')[0]!);
  const вызовыПравила = найтиВызовы(подПравилом);

  it('инвентарь английских имён совпадает с разобранным: реестр не принёс нового', () => {
    const было = Object.keys(ЗАПИСАНО).sort();
    const стало = найдено.map(ключ).sort();

    expect(
      стало,
      'в примитивах реестра изменился набор жёстко зашитых английских имён. ' +
        'Скорее всего прошёл «npx shadcn add». Разбери новое имя и допиши его в ЗАПИСАНО: ' +
        'произносится ли оно и может ли вызов его перекрыть.',
    ).toEqual(было);
  });

  it('каждый вызов примитива под правилом несёт свой aria-label', () => {
    const голые = вызовыПравила.filter((в) => !в.сИменем);

    expect(
      голые.map((в) => `${в.примитив} в ${в.файл}:${в.строка}`),
      'вызов примитива реестра идёт голым, и его доступное имя будет английским. ' +
        'Правится НА ВЫЗОВЕ: aria-label из словаря. Внутри components/ui чинить нельзя — ' +
        'файл перезапишет реестр.',
    ).toEqual([]);
  });

  // ТРИ ЧИСЛА, БЕЗ КОТОРЫХ ВСЁ ВЫШЕ ЗЕЛЕНО НАВСЕГДА. Пустой список голых
  // вызовов неотличим от обхода, который ничего не нашёл; пустой инвентарь
  // неотличим от испорченного выражения. Числа замерены 17.09, не оценены.
  //
  // Число упало — сперва выяснить, ЧТО пропало: вызов убрали нарочно (поправить
  // число и сказать почему) или обход перестал видеть (чинить обход).
  // Подгонять число под наблюдение нельзя — так сторож и умирает.
  it('сам обход жив: находит примитивы, файлы и вызовы', () => {
    expect(найдено.length, 'инвентарь пуст — сломано выражение, а не реестр').toBeGreaterThanOrEqual(6);
    expect(вызовы().length, 'обход не нашёл файлов вызова — сломан обход').toBeGreaterThanOrEqual(157);
    expect(
      вызовыПравила.length,
      'ни одного вызова примитива под правилом — правило проверяет пустоту',
    ).toBeGreaterThanOrEqual(2);
  });

  // Условие 3 приёмки: сторож не должен находить сам себя. Проверяется числом,
  // а не словом — в обходе не должно быть ни одного файла проверок.
  it('и не находит сам себя: в обходе нет ни одного файла проверок', () => {
    const свои = вызовы().filter((п) => п.includes('__tests__') || /\.test\.tsx?$/.test(п));
    expect(свои, 'сторож обходит собственные файлы — он будет зелёным от своего же текста').toEqual([]);
  });
});
