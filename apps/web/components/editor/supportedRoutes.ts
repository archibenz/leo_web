// Где режим правки вообще работает.
//
// Список нужен, потому что переключатель живёт в чроме (то есть на ВСЕХ
// страницах витрины), а провайдер и точки правки — только на тех страницах,
// которые их расставили. Без этой проверки владелец на /ru/shop?edit=1 видел бы
// подпись «Закончить правку», не видел бы ни полосы, ни рамок — и правил бы
// опубликованные данные, считая, что правит черновик.
//
// Добавляя страницу в редактор, добавляйте её и сюда: одно без другого даёт
// либо немой переключатель, либо недостижимую правку.
const EDITABLE = [
  /^\/[^/]+\/?$/, // главная
  /^\/[^/]+\/product\/[^/]+\/?$/, // карточка товара
];

export function supportsEditing(pathname: string): boolean {
  return EDITABLE.some((route) => route.test(pathname));
}
