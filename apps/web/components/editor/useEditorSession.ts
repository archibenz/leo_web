'use client';

import {useWhiteAuth} from '../../hooks/useWhiteAuth';

// Отвечает ровно на один вопрос: «этот посетитель — редактор?».
//
// Это ТОЛЬКО про показ кнопки. Право на черновик даёт бэкенд: ручка
// предпросмотра лежит под ROLE_ADMIN, и посторонний не получит черновых данных,
// даже если нарисует себе кнопку в консоли.
//
// ─── Почему здесь больше нет собственного механизма ───
//
// Раньше хук держал своё: запрос к `/api/auth/me` ради поля `role`, кэш роли в
// `sessionStorage`, дедупликацию обещаний и запоминание отказа на минуту. Он
// порождал ровно две поломки, и обе — следствие того, что роль хранилась
// отдельно от пользователя:
//
// 1. **Админ-панель появлялась только после перезагрузки.** Эффект стоял с
//    пустым списком зависимостей и спрашивал токен ОДИН раз при монтировании.
//    Владелец открывает /account гостем — токена нет, роль «посторонний», и
//    эффект больше не повторяется никогда. Он входит на этой же странице,
//    токен ложится в localStorage ПОСЛЕ монтирования, и сказать об этом
//    смонтированным компонентам некому.
//
// 2. **Роль переживала смену пользователя.** Ключ `reinasleo_editor_role` жил
//    в `sessionStorage` на всю вкладку, и не чистил его никто: во всём
//    apps/web `sessionStorage.removeItem` не встречался ни разу. Админ вышел,
//    в той же вкладке вошёл покупатель — и покупателю показывались органы
//    управления сайтом. Прав это не давало, но кнопка, которой не должно
//    быть, — приглашение искать, что за ней.
//
// Лечится это не подпиской поверх прежнего устройства, а тем, что отдельного
// хранилища роли больше нет. `/api/auth/me` отдаёт `role` тем же ответом, из
// которого useWhiteAuth берёт имя и почту (UserResponse.role в API). Значит
// роль обязана жить там же, где пользователь, и меняться вместе с ним.
//
// ─── Что при этом сохранено ───
//
// Всё, ради чего прежний механизм писался, даёт useWhiteAuth своими силами:
//
// * `/api/auth/**` лимитирован десятью запросами в минуту на IP, и хук зовут
//   три компонента разом (ссылка на админку, переключатель, полоса режима).
//   Дедупликация там своя — `inflight` на уровне модуля, одно обещание на всех.
// * Анонимный посетитель по-прежнему не стоит ни одного запроса: без токена
//   resolveUser() выходит до сети.
// * Отказ по-прежнему не повторяется: `resolved` ставится и в ветке ошибки.
//
// А запросов стало не больше, а МЕНЬШЕ: на странице аккаунта раньше уходило
// два обращения к `/api/auth/me` — одно за пользователем, второе за ролью.
// Теперь одно.

type Session = {checked: boolean; isAdmin: boolean};

export function useEditorSession(): Session {
  const {user, ready} = useWhiteAuth();
  return {checked: ready, isAdmin: user?.role === 'admin'};
}
