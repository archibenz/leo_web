import type {ReactNode} from 'react';

// Переход между страницами витрины.
//
// ПОЧЕМУ ИМЕННО ЗДЕСЬ, А НЕ ВЫШЕ. Next пересоздаёт template.tsx при каждой
// навигации — на этом и держится анимация. Но пересоздаётся ВСЁ ПОДДЕРЕВО, а
// значит и любая обёртка ниже. Поставь я шаблон на уровень `[locale]`, внутрь
// него попали бы обёртки обеих веток — и `(admin)/layout.tsx` с AuthProvider в
// том числе. Тогда каждый переход по админке заново спрашивал бы
// `/api/auth/me` против лимита в десять запросов в минуту: ровно та беда,
// которую мы сегодня чинили на странице аккаунта, только приехавшая с другой
// стороны.
//
// Поэтому шаблонов два — по одному в каждой ветке, ниже её обёртки. Провайдеры
// остаются над ними и переходы переживают.
//
// Проверено замером на живом стенде: при переходе между разделами админки
// обращений к `/api/auth/me` не прибавляется.
export default function ShopTemplate({children}: {children: ReactNode}) {
  return <div className="page-enter">{children}</div>;
}
