import {test, expect, type Page} from '@playwright/test';
import {copy} from '../fixtures/messages';
import {hydrateViaCookieNotice, openWhite} from '../fixtures/white';

// Зоны нажатия витрины на телефоне (lw-8mg4).
//
// Найдено на бою 12.09.2026: ссылки подвала и пункты меню 40 px высотой,
// «политика конфиденциальности» 144×15. Правило проекта (apps/web/CLAUDE.md)
// требует 44×44 — столько занимает подушечка пальца, и меньшая цель читается
// не как «промахнулся», а как «кнопка не работает».
//
// ПОЧЕМУ ОБХОД, А НЕ СПИСОК ПОИМЁННО. Ровно этот же дефект в админке приехал
// оттого, что проверка называла кнопки по именам, а виноватая никем названа не
// была (см. 16-admin-white-shell). Поэтому здесь берётся КАЖДАЯ видимая цель
// внутри шапки, подвала и выдвижного меню, а не перечень.
//
// ШИРИНА ТОЖЕ. Правило говорит 44×44, а не «44 в высоту»: половина целей здесь
// это короткие слова («FAQ», «EN»), и без нижней границы по ширине они
// остаются полосками в двадцать пикселей при честной высоте.

const PHONE = {width: 390, height: 844} as const;

// Порог из apps/web/CLAUDE.md. Живёт здесь один раз, чтобы три обхода не
// разъехались по числам.
const МИНИМУМ = 44;

type Промах = {имя: string; ширина: number; высота: number};
// Обход возвращает не только промахи, но и СКОЛЬКО целей он вообще померил.
// Пустой список промахов сам по себе ничего не доказывает: ровно так же
// выглядит сломанный обход, который не нашёл ни одной цели — и тогда три
// проверки ниже зелены навсегда, в том числе на вернувшихся 32 px. Числом
// целей проверка стережёт сама себя.
//
// Числа ниже — ЗАМЕР 17.09.2026 на 390 px, а не круглая оценка: шапка 4,
// подвал 19, меню 16. Под исключения при этом ушли ровно четверо и все
// названы: ссылка «Перейти к содержанию» (спрятана), поиск в шапке (скрыт до
// md, нулевой размер), «политика конфиденциальности» в согласии и
// «Подробнее» в куки-полосе (обе внутри предложения).
//
// Число упало — сперва выясняем, ЧТО пропало: цель убрали нарочно (тогда
// поправить число и сказать почему) или обход перестал видеть (тогда чинить
// обход). Подгонять число под наблюдение нельзя — так сторож и умирает.
type Обход = {список: Промах[]; измерено: number};

// Обход выполняется в браузере: сравнивать надо то, что реально нарисовано,
// включая раздутие зоны отрицательными полями.
//
// ИСКЛЮЧЕНИЯ НАЗЫВАЮТ СЛУЧАЙ, А НЕ НОСИТЕЛЯ (правило проекта):
//
// 1. Спрятанное от глаза — `clip: rect(0,0,0,0)`, подпись Tailwind sr-only.
//    Такая цель занимает 1×1 и существует для чтения с экрана; пальцем по ней
//    никто не попадает и попадать не должен. Ссылка «к содержимому» в шапке
//    именно такая, пока на неё не встал фокус.
// 2. Ссылка ВНУТРИ предложения — у её родителя есть собственный текст помимо
//    самой ссылки. WCAG 2.5.5 выводит такие из-под правила прямым текстом
//    («The target is in a sentence or block of text»), и не из милосердия:
//    Высокая inline-flex коробка берёт базовую линию от своего содержимого и
//    приподнимает слово над строкой, в которой оно стоит. Так устроены ссылка
//    на политику в согласии под подпиской и такая же в куки-полосе — у обеих
//    в коде стоит объяснение на том же месте.
//
// Обе формулировки — про СЛУЧАЙ. Любая новая спрятанная цель и любая новая
// ссылка внутри абзаца попадут под них сами; новая кнопка в 32 px — нет.
async function промахи(page: Page, корень: string): Promise<Обход> {
  return page.evaluate(
    ([корень, минимум]) => {
      const root = document.querySelector(корень as string);
      if (!root) return {список: [{имя: `${корень}: такого узла на странице нет вовсе`, ширина: 0, высота: 0}], измерено: 0};

      // Есть ли у родителя собственные слова помимо этой ссылки.
      const внутриПредложения = (el: Element): boolean =>
        Array.from(el.parentElement?.childNodes ?? []).some(
          (n) => n.nodeType === Node.TEXT_NODE && (n.textContent ?? '').trim() !== '',
        );

      const цели = root.querySelectorAll('a[href], button, input, select, textarea, summary, [role="button"], [role="link"]');
      let измерено = 0;
      const список = Array.from(цели).flatMap((el) => {
        const r = el.getBoundingClientRect();
        if (r.width === 0 || r.height === 0) return [];
        if (getComputedStyle(el).clip === 'rect(0px, 0px, 0px, 0px)') return [];
        if (внутриПредложения(el)) return [];
        измерено += 1;
        if (r.width >= (минимум as number) && r.height >= (минимум as number)) return [];
        const имя =
          (el.getAttribute('aria-label') || (el as HTMLElement).innerText || el.getAttribute('placeholder') || '')
            .trim()
            .replace(/\s+/g, ' ')
            .slice(0, 40) || el.tagName.toLowerCase();
        return [{имя, ширина: Math.round(r.width), высота: Math.round(r.height)}];
      });
      return {список, измерено};
    },
    [корень, МИНИМУМ] as const,
  );
}

// ВТОРАЯ ПОЛОВИНА ПРАВИЛА. Поднять зону до 44 px можно отрицательными полями —
// и тогда соседние зоны налезают друг на друга. Внутри перекрытия побеждает
// тот, кто ниже по разметке, то есть нажатие уезжает к соседу. Для человека
// это не «мелкая цель», а «нажал одно, открылось другое» — хуже исходной
// беды, и появляется ровно от лечения.
//
// Замерено 17.09 на 390 px: «ОФЕРТА» и «EN» в подвале перекрывались на 43×12,
// нижний край «Оферты» переключал язык. Отсюда и проверка.
//
// ИСКЛЮЧЕНИЯ, СНОВА ПО СЛУЧАЮ:
//
// 1. Вложенность: кнопка внутри ссылки перекрывается с ней по устройству, это
//    одна цель, а не две.
// 2. Прибитое к экрану (`position: fixed`) — такая полоса ЛЕЖИТ поверх
//    страницы по своему назначению, и её пересечение с подвалом не промах
//    разметки, а её работа. Куки-полоса закрывает низ подвала, пока её не
//    закрыли, и должна.
async function перекрытия(page: Page, корень: string): Promise<string[]> {
  return page.evaluate((корень) => {
    const root = document.querySelector(корень as string);
    if (!root) return [`${корень}: такого узла на странице нет вовсе`];

    const прибит = (el: Element): boolean => {
      for (let n: Element | null = el; n && n !== document.body; n = n.parentElement) {
        if (getComputedStyle(n).position === 'fixed') return true;
      }
      return false;
    };

    const цели = Array.from(
      root.querySelectorAll('a[href], button, input, select, textarea, summary, [role="button"], [role="link"]'),
    ).filter((el) => {
      const r = el.getBoundingClientRect();
      return r.width > 1 && r.height > 1 && getComputedStyle(el).clip !== 'rect(0px, 0px, 0px, 0px)' && !прибит(el);
    });

    const имя = (el: Element) =>
      (el.getAttribute('aria-label') || (el as HTMLElement).innerText || el.tagName)
        .trim()
        .replace(/\s+/g, ' ')
        .slice(0, 24);

    const out: string[] = [];
    for (let i = 0; i < цели.length; i++) {
      for (let j = i + 1; j < цели.length; j++) {
        const a = цели[i]!;
        const b = цели[j]!;
        if (a.contains(b) || b.contains(a)) continue;
        const ra = a.getBoundingClientRect();
        const rb = b.getBoundingClientRect();
        const dx = Math.min(ra.right, rb.right) - Math.max(ra.left, rb.left);
        const dy = Math.min(ra.bottom, rb.bottom) - Math.max(ra.top, rb.top);
        if (dx > 0 && dy > 0) out.push(`${имя(a)} ∩ ${имя(b)} = ${Math.round(dx)}×${Math.round(dy)}`);
      }
    }
    return out;
  }, корень);
}

function перечислить(список: Промах[]): string {
  return список.map((п) => `${п.имя} — ${п.ширина}×${п.высота}`).join('; ');
}

test.describe('витрина на телефоне: по каждой цели можно попасть пальцем', () => {
  test.beforeEach(async ({page}) => {
    await page.setViewportSize(PHONE);
    await openWhite(page, '/ru');
  });

  test('шапка', async ({page}) => {
    await expect(page.locator('header')).toBeVisible();

    const {список, измерено} = await промахи(page, 'header');
    expect(измерено, 'обход шапки не нашёл ни одной цели — сломан он, а не вёрстка').toBeGreaterThanOrEqual(4); // замер 17.09: ровно 4
    expect(список, `в шапке цели мельче ${МИНИМУМ}px: ${перечислить(список)}`).toEqual([]);

    // Логотип — 19 px в высоту, и его зону пришлось растить. Растить её было
    // куда: бургер слева и корзина справа стоят на своих 44 px, и между ними
    // есть воздух. Проверка держит это свойство.
    expect(await перекрытия(page, 'header'), 'зоны нажатия в шапке налезают друг на друга').toEqual([]);
  });

  // Куки-полоса живёт внутри <footer> и на первом заходе перекрывает его низ,
  // поэтому её кнопка меряется тем же обходом и в той же жизни, в какой её
  // встречает покупатель: до того, как он её закрыл.
  test('подвал, вместе с куки-полосой', async ({page}) => {
    const полоса = page.getByRole('region', {name: copy('footer', 'cookieText')});
    await expect(полоса).toBeVisible();
    await page.locator('footer').scrollIntoViewIfNeeded();

    const {список, измерено} = await промахи(page, 'footer');
    expect(измерено, 'обход подвала не нашёл ни одной цели — сломан он, а не вёрстка').toBeGreaterThanOrEqual(19); // замер 17.09: ровно 19
    expect(список, `в подвале цели мельче ${МИНИМУМ}px: ${перечислить(список)}`).toEqual([]);
    expect(await перекрытия(page, 'footer'), 'зоны нажатия в подвале налезают друг на друга').toEqual([]);
  });

  test('выдвижное меню', async ({page}) => {
    // Куки-полоса появляется эффектом монтирования и ниоткуда больше — её
    // приход и есть доказательство того, что круг клиентских эффектов прошёл.
    // Без этой отсечки нажатие на бургер приходит в ещё не ожившую разметку и
    // молча ничего не делает: первый прогон так и встал на «диалога нет».
    await hydrateViaCookieNotice(page);
    await page.getByRole('button', {name: copy('menu', 'openMenu')}).first().click();

    const панель = page.getByRole('dialog', {name: copy('menu', 'menu')});
    await expect(панель).toBeVisible();
    // Ждём КОНЦА выезда, а не времени: панель едет 560 мс, и обход на полпути
    // мерил бы цели, часть которых ещё за левым краем экрана.
    await expect(панель).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)');

    const {список, измерено} = await промахи(page, '[role="dialog"]');
    expect(измерено, 'обход меню не нашёл ни одной цели — сломан он, а не вёрстка').toBeGreaterThanOrEqual(16); // замер 17.09: ровно 16
    expect(список, `в меню цели мельче ${МИНИМУМ}px: ${перечислить(список)}`).toEqual([]);
    expect(await перекрытия(page, '[role="dialog"]'), 'зоны нажатия в меню налезают друг на друга').toEqual([]);
  });
});
