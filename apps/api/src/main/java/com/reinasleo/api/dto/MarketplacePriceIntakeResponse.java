package com.reinasleo.api.dto;

import java.util.List;

// Ответ возвращает числа, а не только код 200: отправитель обязан проверять
// следствие своего вызова, а не верить статусу. accepted = updated +
// unchanged.
//
// skipped и rejected НЕ сливаются в одно число — это разные диагнозы.
// skipped — строка синтаксически верна, просто такого productId на витрине
// нет: в аналитике 172 артикула, на витрине 87, и ~85 «не найден» каждый
// вечер — это нормальное состояние, не мусор, в errors не попадает. rejected
// — то, что не прошло Bean Validation на входе (сегодня таких строк в этом
// ответе быть не может: биение формы отбивает 400 на весь запрос раньше,
// чем сервис вообще увидит пачку — поле оставлено на будущее, если появится
// причина отклонять СТРОКУ, а не весь запрос). Признак неуспеха у
// отправителя — только rejected; skipped читать как сигнал не нужно, иначе
// однажды витрина уедет, пропусков станет 87 из 87, и это не будет заметно.
public record MarketplacePriceIntakeResponse(
        int accepted,
        int updated,
        int unchanged,
        int skipped,
        int rejected,
        List<MarketplacePriceRowError> errors
) {}
