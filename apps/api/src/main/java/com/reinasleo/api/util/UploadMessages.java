package com.reinasleo.api.util;

/**
 * Тексты отказов загрузки. Общие, потому что отказать может и контроллер (свой
 * порог в 8 МБ), и резолвер multipart ещё до входа в контроллер (потолок тела
 * запроса в 64 МБ), а владелец в обоих случаях должен прочитать одно и то же.
 */
public final class UploadMessages {

    public static final String TELEGRAM_HINT =
            "Пришлите исходник в телеграм — сожму и верну готовый для витрины.";

    public static final String TOO_LARGE_FOR_THE_REQUEST =
            "Файл не влезает в запрос: потолок 64 МБ. " + TELEGRAM_HINT;

    public static final String UNREADABLE_IMAGE =
            "Не удалось разобрать картинку — файл повреждён или это не изображение. "
                    + "Подойдут JPG и PNG. Если это снимок с айфона в формате HEIC, "
                    + "переключите камеру на «Наиболее совместимый» или пришлите его в телеграм.";

    public static final String IMAGE_TOO_LARGE =
            "Снимок тяжелее 32 МБ. " + TELEGRAM_HINT;

    // Потолок площади — отдельно от потолка веса (IMAGE_TOO_LARGE): маленький
    // сжатый файл может объявить в заголовке какие угодно размеры, а
    // ImageIO.read разворачивает растр целиком ещё до того, как мы увидим
    // итоговый вес результата.
    public static final String IMAGE_TOO_MANY_PIXELS =
            "Снимок объявляет больше 50 Мпикс — такой файл не обрабатываем. " + TELEGRAM_HINT;

    // WebP не вычищаем и не пропускаем как есть: переписать чужой файл на диск,
    // ошибившись в разборе контейнера, — значит молча положить на витрину кадр
    // с оставшимися координатами съёмки, а такую ошибку не видно на глаз.
    // Дешевле отказать и попросить формат, который мы умеем разбирать полностью.
    public static final String WEBP_NOT_ACCEPTED =
            "WebP не принимаем — сохраните картинку в JPEG или PNG и загрузите снова.";

    // Тип определяем по самим байтам, а не по заголовку запроса: заявленный
    // Content-Type — с чужих слов, а метаданные снимка выбрасываются по-разному
    // для разных форматов, и довериться ярлыку значило бы разобрать файл не тем
    // путём.
    public static final String CONTENT_TYPE_MISMATCH =
            "Содержимое файла не совпадает с его типом. Подойдут JPG и PNG — пересохраните и загрузите снова.";

    public static final String NOT_AN_IMAGE =
            "Это не картинка. Подойдут JPG и PNG.";

    private UploadMessages() {}
}
