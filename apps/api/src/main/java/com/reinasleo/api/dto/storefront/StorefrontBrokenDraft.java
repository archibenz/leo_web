package com.reinasleo.api.dto.storefront;

/**
 * Строка, черновик которой не читается.
 *
 * Такая строка отдаётся ОПУБЛИКОВАННОЙ — и рядом кладётся вот этот маркер,
 * чтобы владелец видел разницу между «правки не было» и «правка есть, но её
 * не удалось прочитать». Без маркера он решил бы, что правка потерялась, и
 * сделал бы её заново поверх той, что лежит в базе.
 *
 * Поля нарочно совпадают с {@link com.reinasleo.api.dto.admin.storefront.StorefrontDraftSummary}:
 * редактор сводит два списка по одной паре kind+id.
 *
 * @param kind   section | model | set
 * @param id     идентификатор строки (для образа — его UUID)
 * @param key    человеческая ручка строки: слаг блока, слаг модели, ключ образа
 * @param reason чем именно черновик не подошёл — сообщение той же проверки,
 *               которая откажет при публикации
 */
public record StorefrontBrokenDraft(String kind, String id, String key, String reason) {}
