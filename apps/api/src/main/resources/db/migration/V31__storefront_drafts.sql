-- =============================================
-- V31: черновик правки витрины (этап 2, задача 4).
--
-- Витринные таблицы до сих пор были read-only. Редактор на живых страницах
-- открывает их на запись, но покупатель обязан видеть опубликованное, а не
-- то, что владелец сейчас набирает. Отсюда черновик.
--
-- Таблиц-двойников не заводим: у каждой правимой строки появляется колонка
-- draft JSONB — перекрытие опубликованных полей. NULL = черновика нет.
-- Публикация переносит поля в колонки и очищает draft.
--
-- В draft лежит НАМЕРЕНИЕ, в колонках — ФАКТ. Черновик группирует правку, а
-- не владеет данными: после публикации цена варианта живёт в products и
-- нигде больше. Этим наш случай отличается от возврата к двум источникам
-- правды, от которых уходили в этапе 1.
--
-- products.draft НЕТ намеренно: черновик цветового варианта живёт внутри
-- черновика своей модели, под ключом products.id. Владелец правит карточку
-- целиком и жмёт «Опубликовать» один раз — черновик на отдельной строке
-- разъехался бы, и на витрине оказалась бы половина правки. По той же
-- причине состав образа лежит массивом внутри черновика product_sets, а не
-- построчно в product_set_items.
--
-- storefront_sections.status = 'draft' (он уже в CHECK из V29) — это ДРУГОЕ:
-- новый, ещё ни разу не опубликованный блок. draft JSONB — правка
-- существующего. Не путать.
--
-- Один черновик на строку: «последний правивший побеждает». Для одного
-- владельца приемлемо; при появлении второго редактора это надо пересмотреть.
-- =============================================

ALTER TABLE product_models      ADD COLUMN draft JSONB;
ALTER TABLE product_sets        ADD COLUMN draft JSONB;
ALTER TABLE storefront_sections ADD COLUMN draft JSONB;

COMMENT ON COLUMN product_models.draft IS 'Неопубликованная правка карточки: перекрытие полей модели плюс объект variants, ключ — products.id. NULL = черновика нет';
COMMENT ON COLUMN product_sets.draft IS 'Неопубликованная правка образа: перекрытие полей плюс массив items (состав образа целиком). NULL = черновика нет';
COMMENT ON COLUMN storefront_sections.draft IS 'Неопубликованная правка блока: перекрытие текстов и медиа. NULL = черновика нет; status=draft — это про новый блок, не про правку';
